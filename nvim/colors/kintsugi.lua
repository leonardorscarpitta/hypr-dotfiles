local transparent = vim.g.kintsugi_transparent ~= false
local bg = transparent and c.none or c.ink

local function blend(fg, bgc, alpha)
  local function rgb(h) return tonumber(h:sub(2, 3), 16), tonumber(h:sub(4, 5), 16), tonumber(h:sub(6, 7), 16) end
  local r1, g1, b1 = rgb(fg)
  local r2, g2, b2 = rgb(bgc)
  local mix = function(a, b) return math.floor(a * alpha + b * (1 - alpha) + 0.5) end
  return string.format("#%02x%02x%02x", mix(r1, r2), mix(g1, g2), mix(b1, b2))
end

